import numpy as np
import matplotlib.pyplot as plt

def sphere(x):
  return np.sum(x**2)

def BBO(func, pop_size=20, dim=5, bounds=(-5,5), generation=100, elite_count=2, mutation_rate=0.5):
  lower, upper = bounds
  # Use uniform distribution for continuous domain (sphere function)
  pop = np.random.uniform(lower, upper, (pop_size, dim))
  fitness = np.array([func(ind) for ind in pop])

  best_curve = []

  for gen in range(generation):
    # Sort population by fitness (ascending order for minimization)
    idx = np.argsort(fitness)
    pop, fitness = pop[idx], fitness[idx]

    best_curve.append(fitness[0])

    fit_range = fitness.max() - fitness.min()
    if fit_range == 0:
      norm_fit = np.ones_like(fitness)
    else:
      norm_fit = (fitness.max() - fitness) / (fit_range + 1e-9)

    I, E = 1.0, 1.0
    lambda_ = I * (1 - norm_fit)
    mu = E * norm_fit

    new_pop = np.copy(pop)

    # Migration step
    for i in range(pop_size):
      for j in range(dim):
        if np.random.rand() < lambda_[i]:
          if mu.sum() == 0:
            donor = np.random.randint(0, pop_size)
          else:
            prob = mu / mu.sum()
            donor = np.random.choice(pop_size, p=prob)
          new_pop[i, j] = pop[donor, j]

    # Mutation step
    for i in range(elite_count, pop_size):
      for j in range(dim):
        if np.random.rand() < mutation_rate:
          new_pop[i, j] = np.random.uniform(lower, upper)

    # Evaluate new population
    new_fitness = np.array([func(ind) for ind in new_pop])

    # Elitism
    elite, elite_fit = pop[:elite_count].copy(), fitness[:elite_count].copy()
    worst = np.argsort(new_fitness)[-elite_count:]
    new_pop[worst], new_fitness[worst] = elite, elite_fit

    pop, fitness = new_pop, new_fitness

  best_idx = np.argmin(fitness)
  return pop[best_idx], fitness[best_idx], best_curve

# Run the optimization
np.random.seed(42)
best_solution, best_value, best_curve = BBO(sphere, pop_size=20, dim=5, bounds=(-5,5), generation=100, elite_count=2, mutation_rate=0.5)

# Visualization
plt.figure(figsize=(8, 4))
plt.plot(best_curve, linewidth=2)
plt.title("Convergence Curve (BBO)")
plt.xlabel("Generation")
plt.ylabel("Best Fitness (Sphere Value)")
plt.grid(True)
plt.show()

print("Best Solution Found:", best_solution)
print("Best Fitness Value:", best_value)