import random

def state(n):
  # Bug Fix: Use 0 to n-1 so that all rows (including row 0) can contain a queen
  return [random.randint(0, n-1) for _ in range(n)]

def fitness(state):
  n = len(state)
  total_pairs = n*(n-1)//2
  attackers = 0

  for i in range(n):
    for j in range(i+1, n):
      if (state[i] == state[j]) or (abs(state[i] - state[j]) == abs(i - j)):
        attackers += 1

  return total_pairs - attackers

def get_neighbours(state):
  n = len(state)
  neighbours = []

  for row in range(n):
    for col in range(n):
      if state[col] != row:
        neighbour = list(state)
        neighbour[col] = row
        neighbours.append(neighbour)

  return neighbours

def hill_climbing(n):
  current = state(n)
  current_fitness = fitness(current)

  while True:
    neighbours = get_neighbours(current)
    if not neighbours:
      break

    # Find the best neighbor
    neighbour = max(neighbours, key=lambda x: fitness(x))
    neighbour_fitness = fitness(neighbour)

    # Bug Fix: If the best neighbor is not better than the current state, we have reached a local optimum
    if neighbour_fitness <= current_fitness:
      break
    else:
      current, current_fitness = neighbour, neighbour_fitness

  return current, current_fitness

def random_restart_climbing_hill(n, max_restart):
  best_solution = None
  best_fitness = -1
  goal_solution = n*(n-1)//2

  for i in range(1, max_restart + 1):
    current, current_fitness = hill_climbing(n)

    if current_fitness > best_fitness:
      best_solution, best_fitness = current, current_fitness

    if best_fitness == goal_solution:
      print(f"solution found at restart {i}")
      return best_solution, best_fitness

  return best_solution, best_fitness

def print_board(state):
  n = len(state)
  for row in range(n):
    line = " "
    for col in range(n):
      if state[col] == row:
        line += "Q"
      else:
        line += "."
    print(line)
  print("\n")

