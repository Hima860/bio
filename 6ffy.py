import numpy as np
import matplotlib.pyplot as plt

def rastrigin(x):
  x = np.asarray(x)
  A = 10.0
  return A * x.size + np.sum(x**2 - A * np.cos(2 * np.pi * x))

def FFO(func, dim=10, n_fireflies=40, max_iter=100, lb=-5.2, ub=5.2, alpha=0.2, alpha_decay=0.98, gamma=1.0, beta0=1.0, seed=None):
  rng = np.random.default_rng(seed)
  # Initialize fireflies positions
  x = rng.uniform(lb, ub, size=(n_fireflies, dim))
  # Evaluate fitness (light intensity is inversely proportional to fitness for minimization)
  fitness = np.array([func(ind) for ind in x])

  best_history = []
  best_idx = np.argmin(fitness)
  best_sol = x[best_idx].copy()
  best_fitness = fitness[best_idx]
  best_history.append(best_fitness)

  for iteration in range(max_iter):
    for i in range(n_fireflies):
      for j in range(n_fireflies):
        if fitness[j] < fitness[i]:  # Move firefly i towards more attractive firefly j
          r = np.linalg.norm(x[i] - x[j])
          beta = beta0 * np.exp(-gamma * (r**2))

          # Random steps
          random_vec = alpha * (rng.uniform(-0.5, 0.5, dim)) * (ub - lb)

          # Update position
          x[i] = x[i] + beta * (x[j] - x[i]) + random_vec
          x[i] = np.clip(x[i], lb, ub)
          fitness[i] = func(x[i])

    # Track the global best
    curr_best_idx = np.argmin(fitness)
    if fitness[curr_best_idx] < best_fitness:
      best_fitness = fitness[curr_best_idx]
      best_sol = x[curr_best_idx].copy()

    best_history.append(best_fitness)
    alpha *= alpha_decay

  return best_sol, best_fitness, best_history

# Run Firefly Algorithm
best_solution, best_fitness, best_history = FFO(rastrigin, dim=2, max_iter=100, seed=42)

# Plot Convergence
plt.figure(figsize=(8, 4))
plt.plot(best_history, linewidth=2, color='red')
plt.title("Rastrigin Optimization via Firefly Algorithm")
plt.xlabel("Iteration")
plt.ylabel("Best Fitness Value")
plt.grid(True)
plt.show()

print("Best Solution Found:", best_solution)
print("Best Fitness Value:", best_fitness)